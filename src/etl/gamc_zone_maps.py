"""GAMC base map per zone for the app (Ubicar and Mi zona).

The GAMC WMS proxy has a strict rate limit (~12 s between calls) and the app
must work without signal from the first use, so the maps are precomputed here
and bundled in the app, never requested from the phone.

For each zone it downloads GetMap (EPSG:4326, transparent PNG) of the three
layers the project key opens (Limite Distritos, Periurbanos, Drenaje) over a
window centred on the zone, composites them in that order into one PNG and
writes:

- data/gamc/04/zonas/<zone_id>.png
- data/gamc/04/zonas/index.json  (bbox [west, south, east, north] and size per zone)
- app/src/zone/gamc-images.ts    (static imports so Metro bundles the images)

Resumable: zones whose PNG exists are skipped unless --force.

Usage (needs GAMC_API_KEY in .env or the environment):
    uv run python -m src.etl.gamc_zone_maps
"""

from __future__ import annotations

import argparse
import io
import json
import math
import os
import time
from collections.abc import Callable
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
WMS = "https://serviciosgamc.cochabamba.bo/api/gs/wms"
LAYERS = {
    "distritos": "7eb13092-bf0e-493b-aae6-03c43eedda2c",
    "periurbanos": "c52066a1-32fd-4925-81e0-c2dcb8f4238f",
    "drenaje": "d4cea6e3-fc7f-482a-94ad-bd377df78886",
}
# About 6.6 km across: the plot, its neighbours and the nearest channels.
HALF_DEG = 0.03
WIDTH = 768
SLEEP_S = 12  # measured: bursts get HTTP 429, 10-15 s between calls pass
OUT = ROOT / "data" / "gamc" / "04" / "zonas"
APP_INDEX = ROOT / "app" / "src" / "zone" / "gamc-images.ts"


def api_key() -> str:
    env = ROOT / ".env"
    if env.exists():
        for line in env.read_text().splitlines():
            if line.startswith("GAMC_API_KEY="):
                return line.split("=", 1)[1].strip()
    return os.environ.get("GAMC_API_KEY", "")


def window(lat: float, lon: float) -> tuple[list[float], int, int]:
    """Bbox and pixel size with square pixels on the ground at this latitude."""
    bbox = [lon - HALF_DEG, lat - HALF_DEG, lon + HALF_DEG, lat + HALF_DEG]
    height = round(WIDTH / math.cos(math.radians(lat)))
    return [round(v, 5) for v in bbox], WIDTH, height


def getmap(
    get: Callable[..., Any],
    key: str,
    layer: str,
    bbox: list[float],
    w: int,
    h: int,
    sleep: Callable[[float], None] = time.sleep,
) -> bytes:
    params = {
        "service_id": LAYERS[layer],
        "SERVICE": "WMS",
        "VERSION": "1.1.1",
        "REQUEST": "GetMap",
        "LAYERS": "",
        "FORMAT": "image/png",
        "TRANSPARENT": "true",
        "SRS": "EPSG:4326",
        "BBOX": ",".join(str(v) for v in bbox),
        "WIDTH": str(w),
        "HEIGHT": str(h),
    }
    for attempt in range(4):
        r = get(WMS, params=params, headers={"X-Api-Key": key}, timeout=60)
        if r.status_code == 429:
            sleep(SLEEP_S * (attempt + 2))
            continue
        r.raise_for_status()
        if not r.headers.get("content-type", "").startswith("image/"):
            raise RuntimeError(f"{layer}: expected an image, got {r.headers.get('content-type')}")
        return r.content
    raise RuntimeError(f"{layer}: rate limited after retries")


def composite(images: list[bytes]) -> bytes:
    from PIL import Image

    layers = [Image.open(io.BytesIO(b)).convert("RGBA") for b in images]
    base = Image.new("RGBA", layers[0].size, (0, 0, 0, 0))
    for layer in layers:
        base = Image.alpha_composite(base, layer)
    out = io.BytesIO()
    base.save(out, format="PNG", optimize=True)
    return out.getvalue()


def app_index(zone_ids: list[str]) -> str:
    """TypeScript module with one static import per zone image (Prettier style)."""
    names = {z: f"map_{z.lower()}" for z in zone_ids}
    lines = [
        "// Generated by src/etl/gamc_zone_maps.py; do not edit by hand.",
        'import type { ImageSourcePropType } from "react-native";',
        *[f'import {names[z]} from "../../../data/gamc/04/zonas/{z}.png";' for z in zone_ids],
        "",
    ]
    if zone_ids:
        lines += [
            "export const gamcImages: Record<string, ImageSourcePropType> = {",
            *[f"  {z}: {names[z]}," for z in zone_ids],
            "};",
        ]
    else:
        lines.append("export const gamcImages: Record<string, ImageSourcePropType> = {};")
    return "\n".join(lines) + "\n"


def run(
    zones: dict[str, dict[str, Any]],
    out: Path,
    get: Callable[..., Any],
    key: str,
    force: bool = False,
    sleep: Callable[[float], None] = time.sleep,
) -> dict[str, Any]:
    out.mkdir(parents=True, exist_ok=True)
    index_path = out / "index.json"
    index = json.loads(index_path.read_text()) if index_path.exists() else {"zonas": {}}
    first = True
    for zone_id, z in sorted(zones.items()):
        target = out / f"{zone_id}.png"
        bbox, w, h = window(z["lat"], z["lon"])
        if target.exists() and not force and zone_id in index["zonas"]:
            continue
        images = []
        for layer in LAYERS:
            if not first:
                sleep(SLEEP_S)
            first = False
            images.append(getmap(get, key, layer, bbox, w, h, sleep))
        target.write_bytes(composite(images))
        index["zonas"][zone_id] = {"bbox": bbox, "width": w, "height": h}
        index["fuente"] = "GAMC WMS (Limite Distritos, Periurbanos, Drenaje)"
        index["descargado"] = datetime.now(UTC).date().isoformat()
        index_path.write_text(json.dumps(index, ensure_ascii=False, indent=2) + "\n")
        print(f"  {zone_id}: {target.stat().st_size // 1024} KB")
    return index


def main() -> None:
    import requests

    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()
    key = api_key()
    if not key:
        raise SystemExit("GAMC_API_KEY is missing (.env or environment)")
    zones = json.loads((ROOT / "data" / "gamc" / "zones_gamc.json").read_text())
    index = run(zones, OUT, requests.get, key, force=args.force)
    APP_INDEX.write_text(app_index(sorted(index["zonas"])))
    print(f"{len(index['zonas'])} zone maps -> {OUT}")


if __name__ == "__main__":
    main()
